def get_language(state: dict | None = None) -> str:
	if state is None:
		state = load_state()
	language = state.get("language", "en")
	if language not in SUPPORTED_LANGUAGES:
		return "en"
	return language


def t(key: str, state: dict | None = None, **kwargs: object) -> str:
	language = get_language(state)
	template = TRANSLATIONS.get(language, {}).get(key, TRANSLATIONS["en"].get(key, key))
	return template.format(**kwargs)
